# ---------------------------------------------------------------------------
# Verification key derivation (for fallback mode)
# ---------------------------------------------------------------------------

def derive_verification_key(seed: bytes) -> bytes:
    return hkdf(seed, info=b'WBVERKEY-V3', length=16)


def derive_build_id(seed: bytes, build_id_str: str) -> bytes:
    h = hashlib.sha256()
    h.update(seed)
    h.update(b'WBBUILDID-V3')
    h.update(build_id_str.encode('utf-8'))
    return h.digest()[:16]


