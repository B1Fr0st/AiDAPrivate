def main():
    parser = argparse.ArgumentParser(
        description='Generate WB-AES lookup tables at build time'
    )
    parser.add_argument(
        '--seed',
        required=True,
        help='Build seed as a hex string (64 hex chars = 32 bytes)',
    )
    parser.add_argument(
        '--output',
        required=True,
        help='Output file path for the generated C++ header',
    )
    parser.add_argument(
        '--build-id',
        default='',
        help='Build identifier string embedded in the header',
    )
    args = parser.parse_args()

    seed = bytes.fromhex(args.seed)
    if len(seed) != 32:
        sys.stderr.write(
            f'Error: seed must be exactly 32 bytes (64 hex chars), got {len(seed)} bytes\n'
        )
        sys.exit(1)

    tbl = generate_tables(seed)

    verify_no_sbox_signature(tbl)

    test_plaintext = bytes(16)
    test_ciphertext = encrypt_block(tbl, test_plaintext)
    test_vector = test_plaintext + test_ciphertext

    hash_val = table_hash(tbl)

    ver_key = derive_verification_key(seed)
    ver_xor = hkdf(seed, info=b'WBVERKEYXOR-V3', length=16)
    ver_obf = bytes(a ^ b for a, b in zip(ver_key, ver_xor))
    build_id = derive_build_id(seed, args.build_id)

    masked_tbl = generate_masked_tables(tbl, seed)
    verify_masked_tables(tbl, masked_tbl, seed)

    header = emit_header(tbl, test_vector, hash_val, ver_obf, ver_xor, build_id, args.build_id)
    header += '\n' + emit_masked_tables(masked_tbl)

    with open(args.output, 'w', encoding='utf-8', newline='\n') as f:
        f.write(header)

    masked_size = len(serialize_masked_tables(masked_tbl))
    sys.stderr.write(
        f'Generated {args.output}\n'
        f'  Tables: {len(serialize_tables(tbl))} bytes\n'
        f'  Masked tables: {masked_size} bytes\n'
        f'  Test vector: {test_ciphertext.hex()}\n'
        f'  Table hash: {hash_val.hex()}\n'
        f'  Build ID: {build_id.hex()}\n'
        f'  S-Box signature scan: PASS\n'
        f'  Masked table verification: PASS\n'
    )


if __name__ == '__main__':
    main()
